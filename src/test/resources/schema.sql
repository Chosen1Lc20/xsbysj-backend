DROP TABLE IF EXISTS `user`;
DROP TABLE IF EXISTS `file_record`;
DROP TABLE IF EXISTS `topic`;

CREATE TABLE `user` (
    `id` BIGINT NOT NULL PRIMARY KEY,
    `useraccount` VARCHAR(64) NOT NULL,
    `userNo` VARCHAR(64) NOT NULL,
    `password` VARCHAR(255) NOT NULL,
    `name` VARCHAR(64) NOT NULL,
    `role` VARCHAR(32) NOT NULL,
    `department` VARCHAR(128),
    `avatarUrl` VARCHAR(512),
    `createTime` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `EditTime` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UpdateTime` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (`useraccount`),
    UNIQUE (`userNo`)
);

CREATE TABLE `file_record` (
    `id` BIGINT NOT NULL PRIMARY KEY,
    `uploadUserId` BIGINT NOT NULL,
    `fileKey` VARCHAR(512) NOT NULL,
    `fileUrl` VARCHAR(512) NOT NULL,
    `fileType` VARCHAR(32) NOT NULL,
    `fileExtension` VARCHAR(16) NOT NULL,
    `fileName` VARCHAR(255) NOT NULL,
    `fileSize` BIGINT NOT NULL,
    `contentType` VARCHAR(128) NOT NULL,
    `createTime` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `EditTime` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UpdateTime` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (`fileKey`)
);

CREATE TABLE `topic` (
    `id` BIGINT NOT NULL PRIMARY KEY,
    `teacherId` BIGINT NOT NULL,
    `title` VARCHAR(255) NOT NULL,
    `description` TEXT,
    `type` VARCHAR(64),
    `maxStudents` INT NOT NULL DEFAULT 1,
    `status` VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    `reviewerId` BIGINT,
    `auditComment` VARCHAR(1000),
    `reviewTime` TIMESTAMP,
    `createTime` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `EditTime` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UpdateTime` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
